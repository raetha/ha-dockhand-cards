/** Looks up an editor translated string for the current HA language,
 * falling back to English for an unsupported language or missing key. */
export function t(hass: { language?: string; locale?: { language?: string } } | undefined, key: EditorTranslationKey): string {
  const lang = hass?.locale?.language ?? hass?.language ?? 'en';
  return LOCALES[lang]?.[key] ?? en[key];
}
